CREATE TABLE IF NOT EXISTS public.clinic_spend (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  date_time TIMESTAMPTZ NOT NULL DEFAULT now(),
  name TEXT NOT NULL,
  amount NUMERIC NOT NULL CHECK (amount > 0),
  pay_method TEXT NOT NULL
);

ALTER TABLE public.clinic_spend ENABLE ROW LEVEL SECURITY;

CREATE POLICY "clinic_spend_admin_all"
  ON public.clinic_spend FOR ALL
  USING (public.get_user_role() IN ('admin', 'administration'))
  WITH CHECK (public.get_user_role() IN ('admin', 'administration'));

GRANT SELECT, INSERT, UPDATE, DELETE ON public.clinic_spend TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.clinic_spend_id_seq TO authenticated;
