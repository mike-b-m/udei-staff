CREATE TABLE IF NOT EXISTS public.course_program_assignment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  course_program_id BIGINT NOT NULL REFERENCES public.course_program(id) ON DELETE CASCADE,
  year NUMERIC,
  session NUMERIC,
  faculty TEXT,
  pass_grade NUMERIC
);

INSERT INTO public.course_program_assignment (
  course_program_id,
  year,
  session,
  faculty,
  pass_grade
)
SELECT id, year, session, faculty, pass_grade
FROM public.course_program
WHERE faculty IS NOT NULL
   OR year IS NOT NULL
   OR session IS NOT NULL
   OR pass_grade IS NOT NULL;

CREATE TEMP TABLE course_program_id_map ON COMMIT DROP AS
SELECT
  id AS old_id,
  first_value(id) OVER (
    PARTITION BY COALESCE(NULLIF(lower(btrim(courses)), ''), '#' || id::text)
    ORDER BY id
  ) AS canonical_id
FROM public.course_program;

UPDATE public.course_program_assignment AS assignment
SET course_program_id = id_map.canonical_id
FROM course_program_id_map AS id_map
WHERE assignment.course_program_id = id_map.old_id
  AND id_map.old_id <> id_map.canonical_id;

DELETE FROM public.course_program_assignment AS assignment
USING (
  SELECT id, row_number() OVER (
    PARTITION BY course_program_id, year, session, faculty
    ORDER BY id
  ) AS row_number
  FROM public.course_program_assignment
) AS duplicate
WHERE assignment.id = duplicate.id
  AND duplicate.row_number > 1;

DELETE FROM public.course_program AS course
USING course_program_id_map AS id_map
WHERE course.id = id_map.old_id
  AND id_map.old_id <> id_map.canonical_id;

CREATE UNIQUE INDEX IF NOT EXISTS course_program_courses_normalized_key
  ON public.course_program (lower(btrim(courses)))
  WHERE courses IS NOT NULL AND btrim(courses) <> '';

CREATE UNIQUE INDEX IF NOT EXISTS course_program_assignment_unique
  ON public.course_program_assignment (course_program_id, year, session, faculty);

ALTER TABLE public.course_program
  ALTER COLUMN courses TYPE TEXT USING courses::text,
  ALTER COLUMN credit TYPE NUMERIC USING credit::numeric,
  ALTER COLUMN session_subjet TYPE NUMERIC USING session_subjet::numeric,
  ALTER COLUMN hour_session TYPE NUMERIC USING hour_session::numeric,
  ALTER COLUMN total_hour TYPE NUMERIC USING total_hour::numeric,
  ALTER COLUMN created_at SET DEFAULT now();

UPDATE public.course_program SET created_at = now() WHERE created_at IS NULL;
ALTER TABLE public.course_program ALTER COLUMN created_at SET NOT NULL;

ALTER TABLE public.course_program
  DROP COLUMN IF EXISTS faculty,
  DROP COLUMN IF EXISTS year,
  DROP COLUMN IF EXISTS session,
  DROP COLUMN IF EXISTS pass_grade;

ALTER TABLE public.course_program_assignment ENABLE ROW LEVEL SECURITY;

CREATE POLICY "course_program_assignment_select_auth"
  ON public.course_program_assignment FOR SELECT
  USING (auth.uid() IS NOT NULL);

CREATE POLICY "course_program_assignment_modify_admin"
  ON public.course_program_assignment FOR ALL
  USING (public.get_user_role() IN ('admin', 'administration'))
  WITH CHECK (public.get_user_role() IN ('admin', 'administration'));

GRANT SELECT ON public.course_program_assignment TO authenticated;
GRANT INSERT, UPDATE, DELETE ON public.course_program_assignment TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.course_program_assignment_id_seq TO authenticated;

CREATE OR REPLACE VIEW public.course_program_catalog
WITH (security_invoker = true)
AS
SELECT
  assignment.id,
  course.id AS course_program_id,
  course.created_at,
  course.courses,
  course.credit,
  course.session_subjet,
  course.hour_session,
  course.total_hour,
  assignment.faculty,
  assignment.pass_grade,
  assignment.year,
  assignment.session
FROM public.course_program_assignment AS assignment
JOIN public.course_program AS course
  ON course.id = assignment.course_program_id;

GRANT SELECT ON public.course_program_catalog TO authenticated;
